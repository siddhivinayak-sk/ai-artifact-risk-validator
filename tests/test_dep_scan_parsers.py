class TestDepScanScannerParsers:
    """Integration tests for the DepScan scanner with different file types."""

    @pytest.fixture
    def scanner(self) -> DepScanScanner:
        return DepScanScanner()

    def test_scan_pipfile_lock_content(self, scanner: DepScanScanner):
        """Scanner processes Pipfile.lock content."""
        content = """{
    "default": {
        "requests": {"version": "==2.28.0"},
        "flask": {"version": "==2.3.2"}
    }
}"""
        findings = scanner.scan(content, ArtifactType.MCP, "Pipfile.lock")
        # Should not crash; may or may not produce findings
        assert isinstance(findings, list)

    def test_scan_cargo_lock_content(self, scanner: DepScanScanner):
        """Scanner processes Cargo.lock content."""
        content = """[[package]]
name = "serde"
version = "1.0.188"

[[package]]
name = "tokio"
version = "1.32.0"
"""
        findings = scanner.scan(content, ArtifactType.PLUGIN, "Cargo.lock")
        assert isinstance(findings, list)

    def test_scan_go_sum_content(self, scanner: DepScanScanner):
        """Scanner processes go.sum content."""
        content = "github.com/gin-gonic/gin v1.9.1 h1:abc=\n"
        findings = scanner.scan(content, ArtifactType.MCP, "go.sum")
        assert isinstance(findings, list)

    def test_scan_yarn_lock_content(self, scanner: DepScanScanner):
        """Scanner processes yarn.lock content."""
        content = """"express@^4.18.0":
  version "4.18.2"
"""
        findings = scanner.scan(content, ArtifactType.HOOK, "yarn.lock")
        assert isinstance(findings, list)

    def test_scan_pnpm_lock_content(self, scanner: DepScanScanner):
        """Scanner processes pnpm-lock.yaml content."""
        content = """lockfileVersion: '6.0'
packages:
  /express@4.18.2:
    resolution: {integrity: sha512-...}
"""
        findings = scanner.scan(content, ArtifactType.SKILL, "pnpm-lock.yaml")
        assert isinstance(findings, list)

    def test_scan_package_json_with_wildcards(self, scanner: DepScanScanner):
        """Scanner flags wildcard versions in package.json."""
        content = """{
    "dependencies": {
        "express": "*",
        "lodash": "latest"
    }
}"""
        findings = scanner.scan(content, ArtifactType.PLUGIN, "package.json")
        # Should detect wildcard/unpinned versions
        assert isinstance(findings, list)

    def test_scan_requirements_with_unpinned(self, scanner: DepScanScanner):
        """Scanner flags unpinned dependencies in requirements.txt."""
        content = """requests>=2.28.0
flask
numpy==1.24.0
"""
        findings = scanner.scan(content, ArtifactType.SKILL, "requirements.txt")
        assert isinstance(findings, list)
